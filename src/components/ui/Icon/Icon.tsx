export type IconName = keyof typeof ICONS;

interface Run {
  x: number;
  y: number;
  len: number;
}

/** Collapses each row into horizontal runs so an icon is ~12 rects, not 144. */
function toRuns(rows: readonly string[]): Run[] {
  const runs: Run[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x += 1;
        continue;
      }
      let len = 1;
      while (row[x + len] === '#') len += 1;
      runs.push({ x, y, len });
      x += len;
    }
  });
  return runs;
}

const RUNS = Object.fromEntries(
  (Object.keys(ICONS) as IconName[]).map((name) => [name, toRuns(ICONS[name])]),
) as Record<IconName, Run[]>;

export interface IconProps {
  name: IconName;
  /** Rendered size in CSS pixels. Multiples of 12 stay perfectly crisp. */
  size?: number;
  className?: string;
  title?: string;
}

export function Icon({ name, size = 12, className, title }: IconProps) {
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      fill="currentColor"
      role={title ? 'img' : 'presentation'}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      focusable="false"
    >
      {title ? <title>{title}</title> : null}
      {RUNS[name].map((run) => (
        <rect key={`${run.x}-${run.y}`} x={run.x} y={run.y} width={run.len} height={1} />
      ))}
    </svg>
  );
}

export default Icon;
